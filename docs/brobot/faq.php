      <h1>❓ FAQ</h1>
      <p>よくある質問とその回答をまとめています。</p>

      <h2>導入について</h2>

      <h3>Q. 無料で使えますか？</h3>
      <p>
        <strong>A.</strong> はい。兄弟Bot は界隈サーバー向けに無料で配布しています。
        機能制限のある有料プランなどはありません。
      </p>

      <h3>Q. 導入には何が必要ですか？</h3>
      <p>
        <strong>A.</strong> Discord サーバーと、そのサーバーの管理者権限が必要です。
        個室VCを自動作成する機能を使う場合、Bot のロールに「チャンネル管理」権限を
        付与してください。
      </p>

      <h3>Q. 複数のサーバーで使用できますか？</h3>
      <p>
        <strong>A.</strong> 機能ごとに設定と進行状態をサーバー単位で分離して保存しているため、
        複数サーバーで同時に使用できます。同じサーバー内でも、機能ごとに独立して動作します。
      </p>

      <h3>Q. どのサーバーでも使えますか？</h3>
      <p>
        <strong>A.</strong> 兄弟Bot は特定の界隈サーバー向けに調整しているため、
        利用できるサーバーを限定しています。導入可否はサポート窓口までご相談ください。
      </p>

      <h2>機能について</h2>

      <h3>Q. 「v2」が付くコマンドと付かないコマンドの違いは？</h3>
      <p>
        <strong>A.</strong> <code>v2</code> が付くもの（<code>/個室リレーv2</code> など）が現行版です。
        <code>v2</code> の付かない旧コマンドは互換性のために残しており、
        今後変更・削除される可能性があります。新しい機能は v2 系に実装されます。
      </p>

      <h3>Q. 運営スタッフにだけ操作させたい</h3>
      <p>
        <strong>A.</strong> 各機能の設定で「操作ロール」「設定ロール」を指定してください。
        指定したロールを持つ人と管理者だけがボタンを操作できるようになります。
      </p>

      <h3>Q. ラウンド時間は変えられますか？</h3>
      <p>
        <strong>A.</strong> はい。各パネルの「設定」から 1〜60 分の範囲で変更できます。
        既定は 3 分です。
      </p>

      <h3>Q. 途中参加・途中離脱には対応していますか？</h3>
      <p>
        <strong>A.</strong> 対応しています。機能ごとに扱いが異なります。
        個室リレーv2 は「途中参加自動参加」の ON/OFF で自動配置を切り替えられ、
        合コン進行はロビーを待機キューとして扱います。
        詳細は各機能のページを参照してください。
      </p>

      <h2>トラブルシューティング</h2>

      <h3>Q. Bot が反応しません</h3>
      <p>
        <strong>A.</strong> 以下の点をご確認ください。
      </p>
      <ul>
        <li>Bot がサーバーにオンラインで参加しているか</li>
        <li>コマンドを実行するチャンネルで、Bot にコマンド使用の権限があるか</li>
        <li>必要な権限（チャンネル管理・ロール管理・メッセージ管理）が付与されているか</li>
        <li>操作ロールを設定している場合、自分のロールが含まれているか</li>
      </ul>

      <h3>Q. 「権限がありません」と表示されます</h3>
      <p>
        <strong>A.</strong> パネルの操作権限か設定権限が不足しています。
        サーバー管理者に確認するか、各機能の設定でロールを追加してください。
      </p>

      <h3>Q. 個室VCが作成されません</h3>
      <p>
        <strong>A.</strong> 個室作成カテゴリが未設定か、Bot に「チャンネル管理」権限が
        ありません。カテゴリの権限設定で Bot のロールに権限を付与してください。
      </p>

      <h3>Q. Bot を再起動したらパネルが動かなくなりました</h3>
      <p>
        <strong>A.</strong> 進行状態はデータベースに保存されるため、再起動後も復元されます。
        ただしタイマーは復元されないため、ラウンド中だった場合は
        「ラウンド終了」相当の状態にリセットされます。パネルのボタンから再開してください。
      </p>

      <h3>Q. エラーが発生した場合の対処法は？</h3>
      <p>
        <strong>A.</strong> 表示されたエラーメッセージと、実行したコマンド・操作を控えて
        サポート窓口までご連絡ください。<a href="known-issues">既知の不具合</a> に
        同じ事象が載っている場合があります。
      </p>

      <h2>その他</h2>

      <h3>Q. 機能のリクエストはできますか？</h3>
      <p>
        <strong>A.</strong> サポート窓口にて機能リクエストを受け付けています。
        ただし、すべてのリクエストにお応えできるとは限りません。
      </p>

      <h3>Q. バグ報告はどこにすればいいですか？</h3>
      <p>
        <strong>A.</strong> サポート窓口までお願いします。次の情報があると助かります。
      </p>
      <ul>
        <li>発生した日時</li>
        <li>実行したコマンド、または押したボタン</li>
        <li>表示されたエラーメッセージ（スクリーンショット可）</li>
      </ul>

