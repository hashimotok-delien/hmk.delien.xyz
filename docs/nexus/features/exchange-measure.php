      <!-- 計測の仕組み -->
      <!-- ============================================================ -->
      <h2>計測の仕組み</h2>
      <p>交流計測v2 は「生ログを溜めない」方式で動作します。</p>
      <ol>
        <li>VC の入退室・移動を検知し、メモリ上で滞在時間を計測</li>
        <li><strong>60秒ごと</strong>に、滞在時間を<strong>5分バケット</strong>単位の在室記録としてDBへ書き出し</li>
        <li><strong>120秒ごと</strong>に、在室記録から各ランキングのスコアを集計してDBへ保存</li>
        <li><strong>1時間ごと</strong>に、古い在室記録を削除（保持期間は<strong>90日</strong>）</li>
      </ol>
      <div class="table-wrapper"><table>
        <thead><tr><th>定数</th><th>値</th><th>意味</th></tr></thead>
        <tbody>
          <tr><td>バケット幅</td><td>300秒（5分）</td><td>在室記録をまとめる時間の単位</td></tr>
          <tr><td>書き出し間隔</td><td>60秒</td><td>メモリ上の滞在時間をDBへ保存する間隔</td></tr>
          <tr><td>集計間隔</td><td>120秒</td><td>ランキングのスコアを更新する間隔</td></tr>
          <tr><td>保持期間</td><td>90日</td><td>在室記録を保持する期間</td></tr>
          <tr><td>最大表示件数</td><td>100件</td><td>1つのランキングで表示する上限</td></tr>
        </tbody>
      </table></div>

      <h3>スコアが加算される条件</h3>
      <ul>
        <li>同じVC・同じバケットに<strong>2人以上</strong>いること</li>
        <li>同席者が<strong>全員ロール</strong>を持っていること（全員ロール設定時）</li>
        <li>「計測対象時間」が設定されている場合、<strong>2人の滞在時間のうち短い方</strong>がその分数以上であること</li>
        <li>ランキング定義の性別フィルター・対象者フィルター・ルーム条件を満たすこと</li>
        <li>Bot は計測対象外です</li>
      </ul>
      <div class="alert alert-info">
        <p><strong>💡 設定を変えると再集計されます:</strong>
        設定ファイル・ランキング定義・性別ロールのいずれかを変更すると、
        過去の在室記録から<strong>そのランキングのスコアが作り直されます</strong>（保持期間内）。</p>
